using Dependinator.Core.Parsing;
using Dependinator.Roslyn.Parsing;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Dependinator.Roslyn.Tests.Parsing;

public class LocationsTests : IDisposable
{
    readonly string razorPath = Path.Combine(Path.GetTempPath(), $"{Guid.NewGuid():N}.razor");

    public LocationsTests()
    {
        File.WriteAllLines(razorPath, ["<div>Toolbar</div>", "", "@code {", "  int Count { get; set; }", "}"]);
    }

    public void Dispose() => File.Delete(razorPath);

    [Fact]
    public void GetFirstFileSpanOrNoValue_ShouldMapRazorComponentToRazorFile()
    {
        var type = GetType("Toolbar");

        Assert.Equal(new FileSpan(razorPath, 0, 4), Locations.GetFirstFileSpanOrNoValue(type));
    }

    [Fact]
    public void GetFirstFileSpanOrNoValue_ShouldMapRazorCodeMemberToItsRazorLine()
    {
        var member = GetType("Toolbar").GetMembers("Count").Single();

        Assert.Equal(new FileSpan(razorPath, 3, 3), Locations.GetFirstFileSpanOrNoValue(member));
    }

    INamedTypeSymbol GetType(string name)
    {
        // Shaped like the Razor source generator's output, with a path that is not on disk.
        var generated = $$"""
            #pragma checksum "{{razorPath}}" "{8829d00f-11b8-4213-878b-770e8597ac16}" "00"
            // <auto-generated/>
            namespace Test
            {
                public partial class {{name}}
                {
                    protected void BuildRenderTree() { }
            #nullable restore
            #line (4,3)-(4,27) "{{razorPath}}"
              int Count { get; set; }

            #line default
            #line hidden
            #nullable disable
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(generated, path: "Generator/Test/Toolbar_razor.g.cs");
        var compilation = CSharpCompilation.Create("Test", [tree]);
        return compilation.GetTypeByMetadataName($"Test.{name}")!;
    }
}
